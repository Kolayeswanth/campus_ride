CREATE TABLE public.bus_routes (
  id uuid NOT NULL DEFAULT uuid_generate_v4(),
  college_id uuid NOT NULL,
  route_name text NOT NULL,
  route_code text,
  start_name text NOT NULL,
  end_name text NOT NULL,
  start_latitude numeric NOT NULL,
  start_longitude numeric NOT NULL,
  end_latitude numeric NOT NULL,
  end_longitude numeric NOT NULL,
  waypoints jsonb,
  distance_km numeric CHECK (distance_km > 0::numeric),
  estimated_duration_minutes integer CHECK (estimated_duration_minutes > 0),
  schedule jsonb,
  is_active boolean DEFAULT true,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  polyline_data text,
  route_points jsonb,
  CONSTRAINT bus_routes_pkey PRIMARY KEY (id),
  CONSTRAINT bus_routes_college_id_fkey FOREIGN KEY (college_id) REFERENCES public.colleges(id)
);
